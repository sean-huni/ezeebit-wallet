def yaml_str(text):
    return "'" + text.replace("'", "''") + "'"


def rules_yaml():
    out = [f"# {BANNER}", "apiVersion: 1", "groups:", "  - orgId: 1", "    name: ezeebit", "    folder: Ezeebit alerts",
           "    interval: 10s", "    rules:"]
    for r in RULES:
        out += [f"      - uid: {r['uid']}", f"        title: {r['title']}", "        condition: B"]
        out += [f"        # {line}" for line in r["why"]]
        out += ["        data:", "          - refId: A", "            datasourceUid: prometheus",
                f"            relativeTimeRange: {{from: {r['from']}, to: 0}}", "            model:", "              refId: A",
                "              instant: true", "              expr: >-"]
        out += [f"                {line}" for line in r["expr"].split("\n")]
        out += ["          - refId: B", "            datasourceUid: __expr__", "            model:", "              refId: B",
                "              type: threshold", "              expression: A", "              conditions:",
                f"                - evaluator: {{type: gt, params: [{r['threshold']}]}}"]
        if r["noData"]:
            out += [f"        # {line}" for line in r["noData"].split("\n")]
        out += ["        noDataState: OK", "        execErrState: Error"]
        if r.get("forWhy"):
            out += [f"        # {r['forWhy']}"]
        out += [f"        for: {r['for']}", "        labels:",
                f"          severity: {r['severity']}", "        annotations:",
                f"          summary: {yaml_str(r['summary'])}", f"          runbook: {yaml_str(r['runbook'])}",
                "          __dashboardUid__: ezeebit-alerts", f"          __panelId__: '{rule_panel_id(r)}'"]
    return "\n".join(out) + "\n"


def promtool_yaml():
    out = [f"# {BANNER}", "# The Grafana rules as Prometheus rules: same expression, same threshold, same hold, so",
           "# promtool can test what Grafana evaluates. Grafana-only settings (noDataState) are not mirrored.",
           "groups:", "  - name: ezeebit-mirror", "    interval: 10s", "    rules:"]
    for r in RULES:
        out += [f"      - alert: {r['title']}", "        expr: |-", "          ("]
        out += [f"            {line}" for line in r["expr"].split("\n")]
        out += [f"          ) > {r['threshold']}", f"        for: {r['for']}", "        labels:",
                f"          severity: {r['severity']}"]
    return "\n".join(out) + "\n"


