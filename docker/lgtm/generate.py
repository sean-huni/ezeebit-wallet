class Board:
    def __init__(self):
        self.panels = []
        self.y = 0
        self.x = 0
        self.row_h = 0

    def row(self, title, collapsed_panels=None):
        """A collapsed row holds its panels and queries nothing until a reader opens it."""
        self._newline()
        inner = []
        for panel, w, h in collapsed_panels or []:
            panel["gridPos"] = {"x": 0, "y": self.y + 1, "w": w, "h": h}
            inner.append(panel)
        self.panels.append({"type": "row", "title": title, "collapsed": bool(inner),
                            "gridPos": {"x": 0, "y": self.y, "w": 24, "h": 1}, "panels": inner})
        self.y += 1

    def add(self, panel, w, h):
        if self.x + w > 24:
            self._newline()
        panel["gridPos"] = {"x": self.x, "y": self.y, "w": w, "h": h}
        self.panels.append(panel)
        self.x += w
        self.row_h = max(self.row_h, h)

    def _newline(self):
        if self.x:
            self.y += self.row_h
        self.x = 0
        self.row_h = 0

    def numbered(self):
        n = 0
        for p in self.panels:
            for q in [p] + p.get("panels", []):
                n += 1
                q["id"] = n
        return self.panels


def prom(expr, legend, exemplar=False, instant=False):
    t = {"refId": "A", "datasource": PROM, "expr": expr, "legendFormat": legend}
    if instant:
        t["instant"] = True
        t["range"] = False
    else:
        t["range"] = True
    if exemplar:
        t["exemplar"] = True
    return t


def targets(*ts):
    out = []
    for i, t in enumerate(ts):
        t = dict(t)
        t["refId"] = chr(ord("A") + i)
        out.append(t)
    return out


def timeseries(title, description, tlist, unit="short", links=None, thresholds=None, stack=False, style="dashed",
               min_max=None, overrides=None):
    defaults = {"unit": unit, "custom": {"lineWidth": 2, "fillOpacity": 12, "showPoints": "never", "spanNulls": True,
                                         "gradientMode": "opacity"}}
    if stack:
        defaults["custom"]["stacking"] = {"mode": "normal", "group": "A"}
    if links:
        defaults["links"] = links
    if min_max:
        defaults.update({k: v for k, v in zip(("min", "max"), min_max) if v is not None})
    if thresholds is not None:
        defaults["thresholds"] = {"mode": "absolute", "steps": [{"color": "green", "value": None},
                                                                  {"color": "red", "value": thresholds}]}
        defaults["custom"]["thresholdsStyle"] = {"mode": style}
    return {"type": "timeseries", "title": title, "description": description, "datasource": PROM,
            "targets": targets(*tlist), "fieldConfig": {"defaults": defaults, "overrides": overrides or []},
            "options": {"legend": {"displayMode": "table", "placement": "bottom", "calcs": ["lastNotNull", "max"]},
                        "tooltip": {"mode": "multi", "sort": "desc"}}}


def stat(title, description, tlist, unit="short", mappings=None, steps=None, links=None, text_mode="value_and_name"):
    defaults = {"unit": unit}
    if mappings:
        defaults["mappings"] = mappings
    defaults["thresholds"] = {"mode": "absolute", "steps": steps or [{"color": "green", "value": None}]}
    if links:
        defaults["links"] = links
    return {"type": "stat", "title": title, "description": description, "datasource": PROM, "targets": targets(*tlist),
            "fieldConfig": {"defaults": defaults, "overrides": []},
            "options": {"colorMode": "background", "graphMode": "area", "textMode": text_mode, "justifyMode": "center",
                        "reduceOptions": {"calcs": ["lastNotNull"], "fields": "", "values": False}}}


def rate(metric, by, extra="", window=WINDOW):
    sel = ", ".join(x for x in (SEL, extra) if x)
    return f"sum by ({by}) (rate({metric}{{{sel}}}{window}))"


def p95(metric, by, extra="", sel=SEL):
    s = ", ".join(x for x in (sel, extra) if x)
    return f"histogram_quantile(0.95, sum by ({by}, le) (rate({metric}_bucket{{{s}}}{WINDOW})))"


