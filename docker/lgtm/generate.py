def outputs():
    files = {HERE / "dashboards" / name: json.dumps(build(), indent=2) + "\n" for name, build in BOARDS.items()}
    files[HERE / "alerting" / "rules.yaml"] = rules_yaml()
    files[HERE / "alerting" / "promtool" / "rules.yml"] = promtool_yaml()
    return files


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="fail when a generated file differs from the generator")
    args = parser.parse_args()
    files = outputs()
    stale_dashboards = {p for p in (HERE / "dashboards").glob("*.json")} - set(files)
    if args.check:
        drift = [str(p.relative_to(HERE.parent.parent)) for p, text in files.items()
                 if not p.is_file() or p.read_text() != text]
        drift += [f"{p.relative_to(HERE.parent.parent)} (not generated)" for p in sorted(stale_dashboards)]
        if drift:
            print("generate.py --check: drift in " + ", ".join(drift) + "; run python3 docker/lgtm/generate.py")
            return 1
        print(f"generate.py --check: {len(files)} files match the generator ({len(BOARDS)} dashboards, "
              f"{len(RULES)} rules, 1 promtool mirror)")
        return 0
    for p, text in files.items():
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text)
    for p in stale_dashboards:
        p.unlink()
    print(f"generate.py: wrote {len(files)} files")
    return 0


if __name__ == "__main__":
    sys.exit(main())
